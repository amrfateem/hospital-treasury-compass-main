export function guidesForDepartment(deptId: string, custom: CalibrationGuide[]): (BuiltInGuide | CalibrationGuide)[] {
  return [
    ...BUILT_IN_GUIDES.filter(g => g.departments.includes("*") || g.departments.includes(deptId)),
    ...custom.filter(g => g.department === deptId),
  ];
}
const normalize = (s: string) => s.trim().toLowerCase().replace(/[أإآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه").replace(/[ـًٌٍَُِّْ]/g, "").replace(/\s+/g, " ");
export function suggestGuide(deviceType: string, deptId: string): BuiltInGuide | undefined {
  const query = normalize(deviceType);
  if (!query) return undefined;
  const guides = BUILT_IN_GUIDES.filter(g => g.departments.includes("*") || g.departments.includes(deptId));
  return guides.find(g => normalize(g.deviceType) === query)
    ?? guides.find(g => query.includes(normalize(g.deviceType)) || normalize(g.deviceType).includes(query));
}
